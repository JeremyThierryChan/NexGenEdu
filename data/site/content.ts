名字取自《诗经·唐风·采苓》「采苓采苓，首阳之巅」。苓是药草，须上山采得——先看清问题，才谈得上对症。

试课时，采苓会根据学生的作答过程与教师的课堂记录，把薄弱点落到具体知识点上，而不是笼统地说「基础不牢」。报告会区分三类问题：**概念没弄懂**、**方法没掌握**、**习惯性失误**（审题、计算、书写）。三类问题的应对方式完全不同，混在一起就会出现「补了很久没效果」的情况。

报告同时给出下一步建议：优先补哪几个知识点、按什么顺序、大约需要多少课时，以及是否适合当前班型。

