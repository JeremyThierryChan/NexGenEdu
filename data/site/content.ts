在校表现、作业与考试情况只有家长和学生掌握，我们看不到。因此有恒的作用是**把你提供的信息整理成结构化的阶段反馈**：这段时间哪些知识点稳住了、哪些还在反复、与上阶段的对比如何、下一步重点是什么。

