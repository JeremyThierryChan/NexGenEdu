小学阶段以识字写字、朗读积累和口语表达为基础，帮助学生把字词、句子与段落逐步连成完整的表达。我们关注学生是否真的读懂了一段话、能否说出自己的理解，而不只是会做字词题。通过绘本、短文与生活话题，培养朗读、复述、圈画关键信息和写清楚一件事的能力。

