小学成绩好不等于初中跟得上。初中内容密度与抽象程度都上一个台阶，提前预习的价值在于把「第一次接触」放到压力较小的假期与周末。

这门课进度较快，适合学有余力的学生。如果学生课内基础还不稳，建议先上基础小升初。

