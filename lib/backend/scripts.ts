/**
 * 话术专区：机构日常要说的话，按场景整理成**可直接复制的草稿**。
 *
 * ## 为什么是代码里的模板，而不是数据库里的可编辑数据
 *
 * 话术里含**口径**（提前 24 小时请假不扣课时、试课后报满 10 节试课免费、
 * 只报 1 节加收 10%、两种退费口径…）。这些口径的权威实现在代码里：
 *
 *   - 请假与扣课时：`lib/backend/attendance.ts`
 *   - 退费口径：`lib/backend/finance.ts`（默认「按实付比例退」）
 *   - 报价与计费规则：`lib/backend/pricing.ts`
 *   - 咨询要问清的字段：后台「咨询」页（年级 / 科目 / 时间 / 频次 / 是否指定老师）
 *
 * 话术与它们**必须同步改**：口径改了话术没改，就会出现「系统按新规则扣课时、
 * 老师按旧话术跟家长承诺」这种事 —— 那是纠纷。因此当前阶段让话术随版本走
 * （改口径的提交里一起改话术，`npm run check` 会盯着几个关键数字），
 * 等机构要自己改文案时，再照「报价配置」的做法把它做成数据。
 *
 * ## 一条红线：内部信息不进话术
 *
 * 教师分成比例、教师课时费、机构留存、其他学生的信息、内部备注，**一条都不能出现**
 * 在这里（这些话是发给家长的）。自检里有一条断言逐条扫描关键词 ——
 * 不是靠自觉，是机器拦。
 *
 * ## 用法
 *
 * 话术里的 `{学生}` `{剩余课时}` 这类占位符由页面套用真实数据后替换
 * （`fillScript`）；缺的占位符**保持原样**，不替换成空 —— 空着比写错强。
 */

