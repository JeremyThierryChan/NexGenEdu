/* ── 四、纯函数 ──────────────────────────────────────────────────────── */

/** 按 id 找分组。 */
export function findScriptGroup(id: string): ScriptGroup | undefined {
  return SCRIPT_GROUPS.find((group) => group.id === id);
}

/**
 * 筛选话术：按分组 + 关键字（命中场景名或话术正文）。
 *
 * `group` 传空串或 "全部" 表示不限分组；`keyword` 为空表示不限关键字。
 * 关键字**不区分大小写**，也不做拼音匹配 —— 与全局搜索同一口径（「张」≠「章」）。
 */
export function filterScripts(filter: { group?: string; keyword?: string } = {}): Script[] {
  const group = filter.group ?? "";
  const keyword = (filter.keyword ?? "").trim().toLowerCase();

  return SCRIPTS.filter((script) => {
    if (group !== "" && group !== "全部" && script.group !== group) return false;
    if (keyword === "") return true;
    return (
      script.title.toLowerCase().includes(keyword) ||
      script.script.toLowerCase().includes(keyword) ||
      script.when.toLowerCase().includes(keyword)
    );
  });
}

/**
 * 列出这条话术用到的占位符（去重，按出现顺序）。
 *
 * 页面用它提示「还需要填什么」：套用学生数据后仍然缺的占位符要显眼提示，
 * 免得把「{老师}」原样发给家长。
 */
export function scriptPlaceholders(script: Script): string[] {
  const found: string[] = [];
  for (const match of script.script.matchAll(/\{([^{}]+)\}/g)) {
    const name = match[1]!.trim();
    if (name !== "" && !found.includes(name)) found.push(name);
  }
  return found;
}

/**
 * 套用真实数据：把 `{学生}` 这类占位符替换成实际值。
 *
 * 三个约定：
 *   - **缺失的占位符原样保留**（不替换成空）—— 留着 `{老师}` 比留一段空白更容易发现；
 *   - 值里的 `$` 不会被当成正则替换语法（用函数式 replace，避免 `$&` 这类意外）；
 *   - 不做任何格式化，数字与称呼由调用方决定（例如剩余课时传 "3" 而不是 "3.0"）。
 */
export function fillScript(script: Script, vars: Record<string, string> = {}): string {
  return script.script.replace(/\{([^{}]+)\}/g, (whole, name: string) => {
    const value = vars[name.trim()];
    return value === undefined || value === "" ? whole : value;
  });
}

/** 这条话术里还有哪些占位符没填（页面用来提醒）。 */
export function missingPlaceholders(script: Script, vars: Record<string, string> = {}): string[] {
  return scriptPlaceholders(script).filter((name) => {
    const value = vars[name];
    return value === undefined || value === "";
  });
}

/**
 * 把一组话术拼成纯文本（「复制全部」用）。
 *
 * 保留分组标题与场景名，复制到微信或文档里仍然分得清哪条是哪条。
 */
export function scriptsToText(scripts: Script[]): string {
  const groups = new Map<string, Script[]>();
  for (const script of scripts) {
    const list = groups.get(script.group);
    if (list === undefined) groups.set(script.group, [script]);
    else list.push(script);
  }

  const blocks: string[] = [];
  for (const [groupId, list] of groups) {
    const group = findScriptGroup(groupId);
    blocks.push(`【${group?.name ?? groupId}】`);
    for (const script of list) {
      blocks.push(`· ${script.title}（${script.when}）`, script.script, "");
    }
  }
  return blocks.join("\n").trimEnd() + "\n";
}

/** 话术库规模（页面顶部显示「11 个场景组、33 条」）。 */
export type ScriptSummary = {
  groups: number;
  scripts: number;
  /** 每组条数（页面分组筛选上显示）。 */
  perGroup: Array<{ id: string; name: string; count: number }>;
};

export function summarizeScripts(scripts: Script[] = SCRIPTS): ScriptSummary {
  const perGroup = SCRIPT_GROUPS.map((group) => ({
    id: group.id,
    name: group.name,
    count: scripts.filter((script) => script.group === group.id).length,
  }));
  return { groups: SCRIPT_GROUPS.length, scripts: scripts.length, perGroup };
}
